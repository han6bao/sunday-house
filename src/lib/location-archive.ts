/**
 * Sunday House location archive — real places around Seattle + Tacoma,
 * with real photographs (Wikimedia Commons + studio websites).
 * Nothing generated; every card links out to the place or studio.
 */

export type LocationEntry = {
  name: string;
  city: string;
  tags: string[];
  img: string;
  url: string;
  note?: string;
  /** Explicit photo credit; when absent, photoCredit() derives one. */
  credit?: { text: string; href: string };
};

const COMMONS_PATH = "https://commons.wikimedia.org/wiki/Special:FilePath/";

/**
 * Who made the photo on a card. Wikimedia Commons photos link to their own
 * file page (photographer + license live there); business photos are credited
 * to the business and link to its site. Returns null when the source of a
 * photo isn't recorded yet — those images are due to be replaced.
 */
export function photoCredit(l: LocationEntry): { text: string; href: string } | null {
  if (l.credit) return l.credit;
  if (l.img.startsWith(COMMONS_PATH)) {
    const file = l.img.slice(COMMONS_PATH.length).split("?")[0];
    return { text: "Wikimedia Commons", href: `https://commons.wikimedia.org/wiki/File:${file}` };
  }
  const isBusiness = !l.url.includes("maps.google.") && l.tags.some((t) => ["Studio", "Hotel"].includes(t));
  if (isBusiness || (!l.url.includes("maps.google.") && l.img.startsWith("/assets/"))) {
    return { text: l.name.replace(/\s*\(.*\)\s*$/, ""), href: l.url };
  }
  return null;
}

